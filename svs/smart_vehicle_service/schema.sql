CREATE FUNCTION fn_booking_parts_before_insert()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    available_quantity INTEGER;
BEGIN
    SELECT quantity INTO available_quantity
    FROM spare_parts
    WHERE part_id = NEW.part_id
    FOR UPDATE;

    IF available_quantity IS NULL OR available_quantity < NEW.quantity THEN
        RAISE EXCEPTION 'Insufficient spare-part stock';
    END IF;

    UPDATE spare_parts
    SET quantity = quantity - NEW.quantity
    WHERE part_id = NEW.part_id;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_booking_parts_before_insert
BEFORE INSERT ON booking_parts
FOR EACH ROW EXECUTE FUNCTION fn_booking_parts_before_insert();

CREATE FUNCTION fn_booking_parts_after_delete()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE spare_parts
    SET quantity = quantity + OLD.quantity
    WHERE part_id = OLD.part_id;
    RETURN OLD;
END;
$$;

CREATE TRIGGER trg_booking_parts_after_delete
AFTER DELETE ON booking_parts
FOR EACH ROW EXECUTE FUNCTION fn_booking_parts_after_delete();

CREATE FUNCTION fn_booking_history_after_update()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.status IN ('completed', 'cancelled')
       AND NEW.status IS DISTINCT FROM OLD.status THEN
        INSERT INTO service_history (booking_id, service_date, cost, status)
        SELECT NEW.booking_id, NEW.service_date, s.service_cost, NEW.status
        FROM services s
        WHERE s.service_id = NEW.service_id
        ON CONFLICT (booking_id) DO UPDATE
        SET service_date = EXCLUDED.service_date,
            cost = EXCLUDED.cost,
            status = EXCLUDED.status;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_booking_history_after_update
AFTER UPDATE ON bookings
FOR EACH ROW EXECUTE FUNCTION fn_booking_history_after_update();

CREATE FUNCTION fn_booking_total(p_booking_id INTEGER)
RETURNS NUMERIC(10, 2)
LANGUAGE SQL
STABLE
AS $$
    SELECT COALESCE((
        SELECT s.service_cost
        FROM bookings b
        JOIN services s ON s.service_id = b.service_id
        WHERE b.booking_id = p_booking_id
    ), 0) + COALESCE((
        SELECT SUM(bp.quantity * sp.price)
        FROM booking_parts bp
        JOIN spare_parts sp ON sp.part_id = bp.part_id
        WHERE bp.booking_id = p_booking_id
    ), 0)::NUMERIC(10, 2);
$$;

CREATE PROCEDURE sp_customer_booking_summary(
    IN p_customer_id INTEGER,
    INOUT p_booking_count BIGINT,
    INOUT p_completed_count BIGINT
)
LANGUAGE plpgsql
AS $$
BEGIN
    SELECT COUNT(b.booking_id),
           COUNT(b.booking_id) FILTER (WHERE b.status = 'completed')
    INTO p_booking_count, p_completed_count
    FROM customers c
    LEFT JOIN bookings b ON b.customer_id = c.customer_id
    WHERE c.customer_id = p_customer_id
    GROUP BY c.customer_id;

    IF NOT FOUND THEN
        p_booking_count := 0;
        p_completed_count := 0;
    END IF;
END;
$$;

CREATE VIEW v_service_history AS
SELECT h.history_id, b.booking_id, c.customer_id, c.full_name,
       v.vehicle_number, s.service_name AS service_performed,
       h.service_date, m.mechanic_name, h.cost, h.status
FROM service_history h
JOIN bookings b ON b.booking_id = h.booking_id
JOIN customers c ON c.customer_id = b.customer_id
JOIN vehicles v ON v.vehicle_id = b.vehicle_id
JOIN services s ON s.service_id = b.service_id
LEFT JOIN mechanics m ON m.mechanic_id = b.mechanic_id;
