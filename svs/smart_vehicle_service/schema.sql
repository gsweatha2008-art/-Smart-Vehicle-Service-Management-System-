-- PostgreSQL 12+ schema and demo data for Smart Vehicle Service Management System.
-- In pgAdmin, first create a database named smart_vehicle_service, connect to it,
-- then open this file in Query Tool and execute the whole script.

CREATE TABLE IF NOT EXISTS customers (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    phone VARCHAR(20) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS vehicles (
    vehicle_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL,
    vehicle_number VARCHAR(20) NOT NULL UNIQUE,
    vehicle_type VARCHAR(40) NOT NULL,
    brand VARCHAR(60) NOT NULL,
    model VARCHAR(60) NOT NULL,
    manufacturing_year SMALLINT NOT NULL,
    CONSTRAINT uq_vehicle_customer UNIQUE (vehicle_id, customer_id),
    CONSTRAINT fk_vehicles_customer FOREIGN KEY (customer_id)
        REFERENCES customers(customer_id) ON DELETE CASCADE,
    CONSTRAINT chk_vehicle_year CHECK (manufacturing_year BETWEEN 1886 AND 2100)
);

CREATE TABLE IF NOT EXISTS mechanics (
    mechanic_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mechanic_name VARCHAR(100) NOT NULL,
    phone VARCHAR(20) NOT NULL UNIQUE,
    specialization VARCHAR(100) NOT NULL,
    availability VARCHAR(20) NOT NULL DEFAULT 'available',
    CONSTRAINT chk_mechanic_availability
        CHECK (availability IN ('available', 'busy', 'unavailable'))
);

CREATE TABLE IF NOT EXISTS services (
    service_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_name VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(500) NOT NULL,
    service_cost NUMERIC(10, 2) NOT NULL,
    CONSTRAINT chk_service_cost CHECK (service_cost >= 0)
);

CREATE TABLE IF NOT EXISTS bookings (
    booking_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL,
    vehicle_id INTEGER NOT NULL,
    service_id INTEGER NOT NULL,
    mechanic_id INTEGER,
    booking_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    service_date DATE NOT NULL,
    problem_description VARCHAR(1000) NOT NULL DEFAULT '',
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    CONSTRAINT uq_booking_customer UNIQUE (booking_id, customer_id),
    CONSTRAINT fk_bookings_customer FOREIGN KEY (customer_id)
        REFERENCES customers(customer_id) ON DELETE CASCADE,
    CONSTRAINT fk_bookings_vehicle_customer FOREIGN KEY (vehicle_id, customer_id)
        REFERENCES vehicles(vehicle_id, customer_id) ON DELETE CASCADE,
    CONSTRAINT fk_bookings_service FOREIGN KEY (service_id)
        REFERENCES services(service_id) ON DELETE RESTRICT,
    CONSTRAINT fk_bookings_mechanic FOREIGN KEY (mechanic_id)
        REFERENCES mechanics(mechanic_id) ON DELETE SET NULL,
    CONSTRAINT chk_booking_status
        CHECK (status IN ('pending', 'confirmed', 'in_progress', 'completed', 'cancelled')),
    CONSTRAINT chk_service_date CHECK (service_date >= DATE '2000-01-01')
);

CREATE TABLE IF NOT EXISTS spare_parts (
    part_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_name VARCHAR(120) NOT NULL UNIQUE,
    quantity INTEGER NOT NULL DEFAULT 0,
    price NUMERIC(10, 2) NOT NULL,
    supplier VARCHAR(120) NOT NULL,
    CONSTRAINT chk_part_quantity CHECK (quantity >= 0),
    CONSTRAINT chk_part_price CHECK (price >= 0)
);

CREATE TABLE IF NOT EXISTS booking_parts (
    booking_id INTEGER NOT NULL,
    part_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    PRIMARY KEY (booking_id, part_id),
    CONSTRAINT fk_booking_parts_booking FOREIGN KEY (booking_id)
        REFERENCES bookings(booking_id) ON DELETE CASCADE,
    CONSTRAINT fk_booking_parts_part FOREIGN KEY (part_id)
        REFERENCES spare_parts(part_id) ON DELETE RESTRICT,
    CONSTRAINT chk_booking_part_quantity CHECK (quantity > 0)
);

CREATE TABLE IF NOT EXISTS payments (
    payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INTEGER NOT NULL,
    customer_id INTEGER NOT NULL,
    amount NUMERIC(10, 2) NOT NULL,
    payment_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    payment_method VARCHAR(20) NOT NULL,
    payment_status VARCHAR(20) NOT NULL DEFAULT 'pending',
    CONSTRAINT fk_payments_booking FOREIGN KEY (booking_id)
        REFERENCES bookings(booking_id) ON DELETE CASCADE,
    CONSTRAINT fk_payments_booking_customer FOREIGN KEY (booking_id, customer_id)
        REFERENCES bookings(booking_id, customer_id) ON DELETE CASCADE,
    CONSTRAINT fk_payments_customer FOREIGN KEY (customer_id)
        REFERENCES customers(customer_id) ON DELETE CASCADE,
    CONSTRAINT chk_payment_amount CHECK (amount > 0),
    CONSTRAINT chk_payment_method
        CHECK (payment_method IN ('cash', 'card', 'upi', 'bank_transfer')),
    CONSTRAINT chk_payment_status
        CHECK (payment_status IN ('pending', 'paid', 'refunded'))
);

CREATE TABLE IF NOT EXISTS service_history (
    history_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INTEGER NOT NULL UNIQUE,
    service_date DATE NOT NULL,
    cost NUMERIC(10, 2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'completed',
    CONSTRAINT fk_history_booking FOREIGN KEY (booking_id)
        REFERENCES bookings(booking_id) ON DELETE CASCADE,
    CONSTRAINT chk_history_cost CHECK (cost >= 0),
    CONSTRAINT chk_history_status CHECK (status IN ('completed', 'cancelled'))
);

CREATE TABLE IF NOT EXISTS admin (
    admin_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(60) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL
);

